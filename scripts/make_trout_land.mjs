// Generates src/trout-land.js: coastlines and country borders, already projected
// (Natural Earth 1, cropped to 20°S–84°N, where every native trout range sits) as SVG path data.
// The page places species with the same projection constants, so it needs no map library.
//
// Run once, then commit the output:
//   node scripts/make_trout_land.mjs path/to/world-110m.json [path/to/node_modules]
// Input: Natural Earth 1:110m land and countries as TopoJSON (public domain), for example
// data/world-110m.json from github.com/vega/vega-datasets. Needs d3-geo.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const [input, modules = "/opt/npm-tools/node_modules"] = process.argv.slice(2);
if (!input) { console.error("usage: node scripts/make_trout_land.mjs world-110m.json [node_modules]"); process.exit(1); }
const d3 = await import(pathToFileURL(join(modules, "d3-geo/src/index.js")).href);
const topo = JSON.parse(readFileSync(input, "utf8"));

// TopoJSON decoding: delta-encoded, quantized arcs.
const [sx, sy] = topo.transform.scale, [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((arc) => { let x = 0, y = 0; return arc.map(([dx, dy]) => [(x += dx) * sx + tx, (y += dy) * sy + ty]); });
const arcPts = (i) => (i < 0 ? arcs[~i].slice().reverse() : arcs[i]);
const ring = (ids) => { const out = []; ids.forEach((i, n) => { const p = arcPts(i); out.push(...(n ? p.slice(1) : p)); }); return out; };
const geom = (g) => g.type === "Polygon" ? { type: "Polygon", coordinates: g.arcs.map(ring) }
  : g.type === "MultiPolygon" ? { type: "MultiPolygon", coordinates: g.arcs.map((poly) => poly.map(ring)) } : null;

// Land, without islands that sit wholly south of the crop (Antarctica, New Zealand, ...).
const W = 960, LAT_N = 84, LAT_S = -20;
const land = geom(topo.objects.land);
land.coordinates = land.coordinates.filter((poly) => Math.max(...poly[0].map((p) => p[1])) > LAT_S - 1);

// Interior country borders: arcs used by two different countries.
const uses = new Map();
topo.objects.countries.geometries.forEach((g, gi) => {
  const walk = (a) => (Array.isArray(a) ? a.forEach(walk) : uses.set(a < 0 ? ~a : a, (uses.get(a < 0 ? ~a : a) || new Set()).add(gi)));
  walk(g.arcs);
});
const borders = {
  type: "MultiLineString",
  coordinates: [...uses].filter(([i, s]) => s.size > 1 && arcs[i].some((p) => p[1] > LAT_S - 1)).map(([i]) => arcs[i]),
};

const proj = d3.geoNaturalEarth1().scale(1).translate([0, 0]);
const S = (W / 2) / proj([180, 0])[0];
const yN = proj([0, LAT_N])[1] * S, yS = proj([0, LAT_S])[1] * S;
const TY = 4 - yN, H = Math.ceil(yS - yN + 8);
proj.scale(S).translate([W / 2, TY]).precision(0.2);
const path = d3.geoPath(proj).digits(1);

// The page draws the graticule and the globe's edge itself from the same constants.
const out = { w: W, h: H, s: +S.toFixed(6), tx: W / 2, ty: +TY.toFixed(6), latN: LAT_N, latS: LAT_S, land: path(land), borders: path(borders) };
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const body = `// Generated by scripts/make_trout_land.mjs from Natural Earth 1:110m (public domain). Do not edit.\n` +
  `// Natural Earth 1 projection: x = tx + s * X(lon, lat), y = ty - s * Y(lon, lat), lon/lat in radians.\n` +
  `window.TROUT_LAND = ${JSON.stringify(out)};\n`;
writeFileSync(join(root, "src/trout-land.js"), body);
console.log(`src/trout-land.js: ${(body.length / 1024).toFixed(0)} KB, ${W}×${H}, s=${out.s}, ty=${out.ty}`);
